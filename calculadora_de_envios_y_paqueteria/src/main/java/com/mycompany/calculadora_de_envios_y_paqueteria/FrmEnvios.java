    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
     try {

    Envio envio = new Envio();

    envio.setPesoFisico(Double.parseDouble(txtPeso.getText()));
    envio.setLargo(Double.parseDouble(txtLargo.getText()));
    envio.setAncho(Double.parseDouble(txtAncho.getText()));
    envio.setAlto(Double.parseDouble(txtAlto.getText()));
    envio.setDistancia(Double.parseDouble(txtDistancia.getText()));

    envio.calcularEnvio();

    lblPesoVolumetrico.setText(
        String.format("%.2f kg", envio.getPesoVolumetrico()));

    lblPesoDefinitivo.setText(
        String.format("%.2f kg", envio.getPesoDefinitivo()));

    lblCostoPeso.setText(
        String.format("L %.2f", envio.getCostoPeso()));

    lblRecargo.setText(
        String.format("L %.2f", envio.getRecargoDistancia()));

    lblTotal.setText(
        String.format("L %.2f", envio.getTotalPagar()));

} catch (NumberFormatException e) {

    System.out.println("Ingrese valores numericos validos");

} catch (IllegalArgumentException e) {

    System.out.println(e.getMessage());

}
    }//GEN-LAST:event_btnCalcularActionPerformed

